/**
 * キーワードの受け持ち表（Keyword Ownership Map）。「この検索語は、このページが受け持つ」を1か所で決める。
 *
 * - 主キーワード（primary）は1ページに1つ。ほかのページと重ねない（重なると npm run seo:check が落ちる）
 * - ブログ記事はロングテールだけを受け、ここにある固定ページの検索語と重なる題材は公開しない
 *   （lib/blog-generator/validate.ts が lib/seo-map.ts の findCannibalPage で調べる）
 * - priority・pillar・cluster は、内部リンクの監査（npm run seo:audit：P0 は TOP から2クリック以内か、など）に使う
 * - ページを増やす・役割を変えるときは、まずここを直す
 *
 * Node のスクリプト（tsx）からも読むので、"@/…" の別名や fs は使わない。
 */

export interface SeoEntry {
  path: string;
  /** 主キーワード（1ページに1つ・重複禁止） */
  primary: string;
  /** そのページで一緒に受けるキーワード */
  secondary: string[];
  /** 検索意図：このページが答える問い */
  intent: string;
  /** 似たページとの役割の違い */
  role: string;
  /** title と h1 の両方に入っているべき語 */
  must: string[];
  /** 優先度。P0＝評価を集める最重要のページ（TOP から2クリック以内・本文のリンクを多く集める）、P1＝柱を支えるページ、P2＝案内・規約など */
  priority: "P0" | "P1" | "P2";
  /** このページが属する話題の柱（自分が柱なら自分のパス）。本文から柱へリンクする */
  pillar: string;
  /** 話題のまとまり（関連記事・内部リンクの見直しの単位） */
  cluster: string;
  /** 検索の目的の種類。local＝地域の業者を探す／commercial＝サービスを比べる／informational＝調べる／tool＝計算する／transactional＝依頼する／navigational＝特定のページへ */
  intentType: "local" | "commercial" | "informational" | "tool" | "transactional" | "navigational";
  /** 検索結果に出すか。false のページは noindex・sitemap 対象外（中身が揃ってから true にする） */
  index: boolean;
}

