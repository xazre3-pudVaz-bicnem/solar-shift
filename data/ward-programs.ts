export type WardSlug = "adachi" | "sumida" | "edogawa";

export interface WardSource {
  name: string;
  url: string;
  verifiedAt: string;
}

export interface WardProgramItem {
  /** 対象の設備 */
  equipment: string;
  /** 金額の決まり方 */
  amount: string;
  /** 上限 */
  cap: string;
  /** 対象になる機器の条件 */
  requirement?: string;
}

/** 申請の順番の1コマ。apply が、区へ申請するところ */
export interface WardOrderStep {
  label: string;
  note?: string;
  apply?: boolean;
}

export interface WardProgram {
  slug: WardSlug;
  /** ページのタイトル（「｜SOLAR SHIFT」を付ける前）。主キーワード「◯◯区 太陽光 補助金」を先頭に置く */
  title: string;
  /** 検索結果の説明文（120字以内） */
  description: string;
  /** 制度の名前 */
  programName: string;
  fiscalYear: string;
  /** 区の公式ページに書かれている更新日 */
  pageUpdatedAt: string;
  /** 太陽光・蓄電池そのものに、区の補助があるか */
  hasSolarBatterySubsidy: boolean;
  /** 申請の時期（ひとことで） */
  timingLabel: string;
  /** 申請の時期の説明 */
  timing: string;
  /** 申請の順番（図にする）。太陽光・蓄電池の補助が無い区には持たせない */
  order?: WardOrderStep[];
  /** ページ冒頭の結論 */
  conclusion: string;
  points: string[];
  /** 太陽光・蓄電池などのメニュー */
  items: WardProgramItem[];
  /** 受付期間・期限 */
  schedule: { label: string; value: string }[];
  /** 主な条件 */
  conditions: string[];
  /** 国・都の制度との関係 */
  combination: string;
  /** 区が呼びかけている注意（区のページにある内容だけ） */
  cautions: string[];
  /** SOLAR SHIFT に頼む場合に知っておいてほしいこと（正直に書く） */
  notes: string[];
  contact: { name: string; tel?: string };
  /** 内容を最後に書き直した日（確認だけなら進めない） */
  updatedAt: string;
  sources: WardSource[];
  faq: { q: string; a: string }[];
  /** 業者としての案内（施工事例がある区だけ表示する。contractorFor） */
  contractor?: WardContractor;
}

/**
 * 業者として案内するページの中身（施工事例がある区だけで使う。contractorFor を参照）。
 * 葛飾区のページ（/area/katsushika）と同じ狙い方：その区で太陽光・蓄電池を頼める業者を探している人に、
 * 対応の範囲・進め方・その区の住まいの事情・確かめる点・施工事例を示す。
 * 書くのは、区・都の公式ページで確かめたことと、運営者から確認した会社の情報だけ。区名だけを入れ替えた文章にしない。
 */
export interface WardContractor {
  /** 施工事例（data/works.ts の city）と照らす区の名前 */
  wardName: string;
  /** タイトル（「｜SOLAR SHIFT」を付ける前） */
  title: string;
  /** 検索結果の説明文（全角80〜110字） */
  description: string;
  /** ページの冒頭（3行以内で、だれが・どこまで対応し・補助金はどうなっているかに答える） */
  lead: string;
  conclusion: string;
  points: string[];
  /** ご相談から設置までの進め方 */
  flow: { title: string; meta: string; body: string; icon: "mail" | "search" | "calc" | "stamp" }[];
  /** その区の住まい・地域の事情（出典つき） */
  housing: { title: string; body: string; sourceName?: string; sourceUrl?: string }[];
  /** 業者を選ぶとき・申請するときに確かめること（区・都の案内にもとづく） */
  checkpoints: { title: string; body: string }[];
  faq: { q: string; a: string }[];
  sources: WardSource[];
  /** 内容を最後に書き直した日 */
  updatedAt: string;
}

