export interface WardSource {
  name: string;
  url: string;
  verifiedAt: string;
}

export interface WardProgramItem {
  /** 対象の設備 */
  equipment: string;
  /** 金額の決まり方 */
  amount: string;
  /** 上限 */
  cap: string;
  /** 対象になる機器の条件 */
  requirement?: string;
}

/** 申請の順番の1コマ。apply が、区へ申請するところ */
export interface WardOrderStep {
  label: string;
  note?: string;
  apply?: boolean;
}

export interface WardProgram {
  slug: WardSlug;
  /** ページのタイトル（「｜SOLAR SHIFT」を付ける前）。主キーワード「◯◯区 太陽光 補助金」を先頭に置く */
  title: string;
  /** 検索結果の説明文（120字以内） */
  description: string;
  /** 制度の名前 */
  programName: string;
  fiscalYear: string;
  /** 区の公式ページに書かれている更新日 */
  pageUpdatedAt: string;
  /** 太陽光・蓄電池そのものに、区の補助があるか */
  hasSolarBatterySubsidy: boolean;
  /** 申請の時期（ひとことで） */
  timingLabel: string;
  /** 申請の時期の説明 */
  timing: string;
  /** 申請の順番（図にする）。太陽光・蓄電池の補助が無い区には持たせない */
  order?: WardOrderStep[];
  /** ページ冒頭の結論 */
  conclusion: string;
  points: string[];
  /** 太陽光・蓄電池などのメニュー */
  items: WardProgramItem[];
  /** 受付期間・期限 */
  schedule: { label: string; value: string }[];
  /** 主な条件 */
  conditions: string[];
  /** 国・都の制度との関係 */
  combination: string;
  /** 区が呼びかけている注意（区のページにある内容だけ） */
  cautions: string[];
  /** SOLAR SHIFT に頼む場合に知っておいてほしいこと（正直に書く） */
  notes: string[];
  contact: { name: string; tel?: string };
  sources: WardSource[];
  faq: { q: string; a: string }[];
}

